/**
 * src/lib/legacy-build/generate.ts
 *
 * The template generator's logic (accessforge-skeleton task 4.5, design
 * "Build-time generation and verification"), kept pure so the stale-file test
 * runs exactly what the script runs. For each tree: sanitise, serialise, then
 * scan the joined segments with every slot replaced by an escaped hostile
 * probe. Any finding throws with the template name and the construct. GET
 * templates get their Page_Version stamped.
 */

import { escapeHtmlText, findUnsafeConstructs, sanitizeTree, serializeParts, type Node, type SlotName } from './html.js';
import { computePageVersion, stampVersion } from './page-version.js';
import { PAGE_BUILDERS, ROW_BUILDERS, type TemplateName } from './templates.js';

export interface GeneratedTemplate {
  segments: string[];
  slots: SlotName[];
}

/** What a slot could carry, escaped the way the handler escapes it. */
export const HOSTILE_PROBE = escapeHtmlText('<script>x</script>" onload="x');

export class UnsafeTemplateError extends Error {
  constructor(
    readonly template: string,
    readonly constructs: string[],
  ) {
    super(`Template "${template}" contains unsafe constructs: ${constructs.join('; ')}`);
    this.name = 'UnsafeTemplateError';
  }
}

export interface GenerateOptions {
  /** Replaced only in tests, to prove the scan stops a tree the sanitiser did not clean. */
  sanitize?: (tree: Node) => Node;
}

/** Sanitise, serialise and verify one tree. */
export function buildTemplate(name: string, tree: Node, options: GenerateOptions = {}): GeneratedTemplate {
  const parts = serializeParts((options.sanitize ?? sanitizeTree)(tree));
  const probed = parts.segments.join(HOSTILE_PROBE);
  const found = findUnsafeConstructs(probed);
  if (found.length > 0) throw new UnsafeTemplateError(name, found);
  return parts;
}

export interface GeneratedSet {
  templates: Record<TemplateName, GeneratedTemplate>;
  rows: Record<keyof typeof ROW_BUILDERS, GeneratedTemplate>;
  versions: { home: string; register: string };
}

export async function generateAll(builders: Record<TemplateName, () => Node> = PAGE_BUILDERS, options: GenerateOptions = {}): Promise<GeneratedSet> {
  const templates = {} as Record<TemplateName, GeneratedTemplate>;
  for (const name of Object.keys(builders) as TemplateName[]) templates[name] = buildTemplate(name, builders[name](), options);

  const versions = { home: '', register: '' };
  for (const name of ['home', 'register'] as const) {
    const t = templates[name];
    if (t.slots.length > 0) throw new Error(`GET template "${name}" must have no slots`);
    const version = await computePageVersion(t.segments[0]!);
    templates[name] = { segments: [stampVersion(t.segments[0]!, version)], slots: [] };
    versions[name] = version;
  }

  const rows = {} as Record<keyof typeof ROW_BUILDERS, GeneratedTemplate>;
  for (const name of Object.keys(ROW_BUILDERS) as Array<keyof typeof ROW_BUILDERS>) rows[name] = buildTemplate(`row ${name}`, ROW_BUILDERS[name]());
  return { templates, rows, versions };
}

/** The committed module text of src/worker/legacy/generated/templates.ts. */
export function renderModule(set: GeneratedSet): string {
  const json = (v: unknown) => JSON.stringify(v, null, 2);
  return `/**
 * src/worker/legacy/generated/templates.ts
 *
 * GENERATED by scripts/build-legacy-templates.ts from src/lib/legacy-build/.
 * Do not edit by hand: run \`npm run build:legacy\`. A unit test fails when this
 * file is stale. Every template was sanitised and scanned for unsafe
 * constructs at build time; the Worker only joins segments with escaped values.
 */

export type SlotName = 'reference' | 'summaryRows' | 'failingNames' | 'name' | 'value';

export interface GeneratedTemplate {
  /** segments.length === slots.length + 1 */
  readonly segments: readonly string[];
  readonly slots: readonly SlotName[];
}

export const TEMPLATES: Readonly<Record<'home' | 'register' | 'confirmation' | 'error' | 'notFound', GeneratedTemplate>> = ${json(set.templates)};

export const ROW_TEMPLATES: Readonly<{ summaryRow: GeneratedTemplate; failingName: GeneratedTemplate; unknownField: GeneratedTemplate }> = ${json(set.rows)};

export const PAGE_VERSIONS = ${json(set.versions)} as const;
`;
}
